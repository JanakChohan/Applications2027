def esc(s):
    return html.escape(s, quote=False)


def cards():
    out = []
    for i, (label, jd, scen) in enumerate(LADDER, 1):
        out.append(f'<h3>{i}. {esc(label)}</h3><p class="small"><b>JD line:</b> "{esc(jd)}"</p>')
        for lvl, (t, setup, trap, say, why, twist, hold) in zip(("easy", "medium", "hard"), scen):
            out.append(f'''<div class="card {lvl}"><div class="ch"><span class="ct">{esc(t)}</span><span class="lvl">{lvl}</span></div>
<dl><dt>Setup</dt><dd>{esc(setup)}</dd><dt>Trap</dt><dd>{esc(trap)}</dd><dt>Say</dt><dd>{esc(say)}</dd>
<dt>Why</dt><dd>{esc(why)}</dd><dt>Twist</dt><dd>{esc(twist)}</dd><dt>Hold</dt><dd>{esc(hold)}</dd></dl></div>''')
    return "\n".join(out)


if __name__ == "__main__":
    with open(os.path.join(ROOT, "fragments", "ladder_cards.html"), "w") as f:
        f.write(cards())
    print(sum(len(x[2]) for x in LADDER), "cards")
